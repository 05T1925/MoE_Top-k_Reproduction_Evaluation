"""TEST_ONLY bridge to the repository's actual Protocol I uCMP/DCF implementation."""
from __future__ import annotations

import subprocess
from collections import defaultdict
from pathlib import Path
from typing import Any

import numpy as np


MASK64 = (1 << 64) - 1


def stable_low_to_high_key(score: int, original_index: int, n: int) -> int:
    """Project stable key: signed score ascending, then original_index descending."""
    b = max(1, (n - 1).bit_length())
    ordered = (score & 0xFFFFFFFF) ^ 0x80000000
    return (ordered << b) + (n - 1 - original_index)


def item_code(item: Any, n: int, k: int, low_pad: int) -> int:
    """S6 exact no-tag-bit layout, evaluated only by this plaintext harness."""
    b = max(1, (n - 1).bit_length())
    rmax = ((1 << 32) - 1) * (1 << b) + (n - 1)
    if item.category == 0:
        detail = int(item.label.rsplit(":", 1)[1])
        code = detail
    elif item.category == 1:
        code = low_pad
    elif item.category == 2:
        code = low_pad + 1 + stable_low_to_high_key(item.score, item.original_index, n)
    elif item.category == 3:
        code = low_pad + rmax + 2
    elif item.category == 4:
        detail = int(item.label.rsplit(":", 1)[1])
        code = low_pad + rmax + 3 + detail
    else:
        raise ValueError("unknown dummy category")
    # ProtocolIUcmpMaterial's no-wrap input interval is [0,2^(bits-1));
    # the S6 numeric code range needs 33+b bits, hence comparator width 34+b.
    bits = 34 + b
    if code >= (1 << bits):
        raise ValueError(f"S6 TEST_ONLY code exceeds declared width n={n}, K={k}")
    return code


class FssBackend:
    """One-shot actual FSS materials, generated by the TEST_ONLY controller."""

    def __init__(self, executable: str | Path, seed: int):
        executable_text = str(executable)
        if executable_text.startswith("wsl:"):
            command = ["wsl.exe", "-d", "Ubuntu-24.04", "--", executable_text[4:], str(seed)]
        else:
            command = [executable_text, str(seed)]
        self.process = subprocess.Popen(
            command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, text=True, encoding="ascii", errors="replace", bufsize=1,
        )
        if self.process.stdin is None or self.process.stdout is None:
            raise RuntimeError("failed to open FSS test backend pipes")
        self.round_slots: dict[int, int] = defaultdict(int)
        self.round_reverse_complements: dict[int, int] = defaultdict(int)
        self.round_logical_calls: dict[int, int] = defaultdict(int)
        self.membership_slots = 0
        self.membership_reverse_complements = 0

    def _request(self, line: str) -> list[str]:
        assert self.process.stdin is not None and self.process.stdout is not None
        self.process.stdin.write(line + "\n")
        self.process.stdin.flush()
        response = self.process.stdout.readline()
        if not response:
            tail = self.process.stderr.read()[-1000:] if self.process.stderr is not None else ""
            raise RuntimeError(f"FSS test backend exited without a response: {tail}")
        return response.split()

    def _compare_shares(self, left: int, right: int, bits: int = 43) -> tuple[int, int]:
        response = self._request(f"C {bits} {left} {right}")
        if len(response) != 3 or response[0] != "C":
            raise RuntimeError(f"malformed FSS comparator response: {response}")
        c0, c1 = int(response[1]), int(response[2])
        if ((c0 + c1) & MASK64) not in (0, 1):
            raise RuntimeError("actual uCMP shares did not reconstruct to a bit")
        return c0, c1

    @staticmethod
    def _open_bit(shares: tuple[int, int]) -> int:
        return (shares[0] + shares[1]) & MASK64

    def compare_batches(self, round_no: int, batches: list[dict[str, Any]],
                        items: list[Any], n: int, k: int, low_pad: int) -> np.ndarray:
        # Cache scope is exactly one causal round and one partition task.  No
        # cross-round or cross-instance key/share cache is used.
        shares_by_edge: dict[tuple[str, int, int], tuple[int, int]] = {}
        codes = [item_code(item, n, k, low_pad) for item in items]
        bits = 34 + max(1, (n - 1).bit_length())
        total_calls = 0
        reverse_calls = 0
        results: list[np.ndarray] = []
        for batch in batches:
            left = batch["left"]
            right = batch["right"]
            task = batch["descriptor"]["task"]
            output = np.empty(len(left), dtype=np.bool_)
            for index, (left_id_raw, right_id_raw) in enumerate(zip(left, right)):
                left_id, right_id = int(left_id_raw), int(right_id_raw)
                if left_id == right_id:
                    raise ValueError("self-comparison is not a valid edge")
                lo, hi = sorted((left_id, right_id))
                key = (task, lo, hi)
                if key not in shares_by_edge:
                    shares_by_edge[key] = self._compare_shares(codes[lo], codes[hi], bits)
                base = shares_by_edge[key]
                total_calls += 1
                if left_id == lo:
                    opened = self._open_bit(base)
                else:
                    # Affine conversion in Z/(2^64): shares of 1-c are
                    # (1-c0, -c1).  Preserve one-shot key usage.
                    complement = ((1 - base[0]) & MASK64, (-base[1]) & MASK64)
                    opened = self._open_bit(complement)
                    reverse_calls += 1
                output[index] = bool(opened)
            self.round_logical_calls[round_no] += len(output)
            results.append(output)
        slots = len(shares_by_edge)
        self.round_slots[round_no] += slots
        self.round_reverse_complements[round_no] += reverse_calls
        return np.concatenate(results) if results else np.empty(0, dtype=np.bool_)

    def compare_values(self, left: int, right: int, bits: int = 43) -> tuple[int, int]:
        return self._compare_shares(left, right, bits)

    def stop(self) -> None:
        if self.process.poll() is None:
            self._request("Q")
        code = self.process.wait(timeout=5)
        stderr_text = self.process.stderr.read() if self.process.stderr is not None else ""
        if code != 0:
            raise RuntimeError(f"FSS test backend exit code {code}: {stderr_text[-1000:]}")
